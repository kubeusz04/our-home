let serial = 0;
function item(
  kind: FurnitureKind,
  roomId: string,
  x: number,
  z: number,
  opts: Partial<FurnitureItem> = {},
): FurnitureItem {
  const c = catalog.find((c) => c.kind === kind)!;
  return {
    ...c,
    id: `seed-${++serial}`,
    roomId,
    x,
    z,
    y: 0,
    rotation: 0,
    cost: 0,
    notes: "",
    purchased: false,
    vase: "ceramic",
    enabled: true,
    ...opts,
  };
}
